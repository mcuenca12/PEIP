-- Evento listo para pintar: etiquetas, precio minimo y afinidad del usuario en
-- sesion (null si la personalizacion esta apagada). Respeta la RLS de quien
-- consulta. Si se agregan columnas a la vista, hay que recrear las funciones
-- que devuelven setof v_evento.
create view v_evento
with (security_invoker = true) as
select
  e.id_evento,
  e.titulo,
  e.eslogan,
  e.descripcion,
  e.fecha_inicio,
  e.fecha_fin,
  e.todo_el_dia,
  e.lugar,
  e.estado,
  e.aforo,
  e.imagen_path,
  e.id_categoria,
  e.id_organizador,
  e.id_ciudad,
  e.id_serie,
  e.id_evento_anterior,
  coalesce((select array_agg(ee.id_etiqueta order by ee.id_etiqueta)
            from evento_etiqueta ee
            where ee.id_evento = e.id_evento), '{}'::integer[]) as id_etiquetas,
  (select min(t.precio) from tipo_entrada t
   where t.id_evento = e.id_evento) as precio_minimo,
  case when u.personalizacion_activa then afinidad(e.id_evento) end as afinidad
from evento e
left join usuario u on u.id_usuario = auth.uid();

-- Listado de Explorar: eventos vigentes, con filtro opcional de categoria,
-- ordenados por afinidad y luego por fecha. Con la personalizacion apagada la
-- afinidad es null y el orden queda solo por fecha.
create function recomendar_eventos(p_id_categoria integer default null)
returns setof v_evento
language sql
stable
set search_path = ''
as $$
  select v.*
  from public.v_evento v
  where v.estado <> 'cancelado'
    and (p_id_categoria is null or v.id_categoria = p_id_categoria)
  order by v.afinidad desc nulls last, v.fecha_inicio asc;
$$;

-- Eventos que cumplen un tsquery, usando el indice GIN. Orden: relevancia,
-- afinidad, fecha.
create function buscar_eventos_tsq(p_tsq tsquery)
returns setof v_evento
language sql
stable
set search_path = ''
as $$
  select v.*
  from public.evento e
  join public.v_evento v on v.id_evento = e.id_evento
  where e.busqueda @@ p_tsq
    and v.estado <> 'cancelado'
  order by ts_rank(e.busqueda, p_tsq) desc,
           v.afinidad desc nulls last,
           v.fecha_inicio asc;
$$;

-- Busqueda por significado. Primero pide eventos que cubran todos los conceptos
-- de la consulta; si no hay ninguno, acepta los que cubran alguno. Si tampoco
-- hay, devuelve cero filas y la app decide mostrar los eventos mas cercanos con
-- recomendar_eventos().
create function buscar_eventos(p_consulta text)
returns setof v_evento
language plpgsql
stable
set search_path = ''
as $$
begin
  return query
    select * from public.buscar_eventos_tsq(public.peip_tsquery(p_consulta, true));
  if found then
    return;
  end if;
  return query
    select * from public.buscar_eventos_tsq(public.peip_tsquery(p_consulta, false));
end;
$$;
