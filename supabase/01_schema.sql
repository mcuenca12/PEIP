-- ---------------------------------------------------------------------------
-- 4. Alta de usuario: perfil y organizador propios
-- ---------------------------------------------------------------------------
-- Se hace en un trigger y no desde la app porque con confirmacion de correo
-- activada signUp no devuelve sesion y un insert del cliente fallaria por RLS.
-- La app pasa nombre e id_ciudad en options.data de signUp.

create function handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_nombre text;
  v_ciudad integer;
begin
  v_nombre := coalesce(
    nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''),
    split_part(new.email, '@', 1)
  );
  v_ciudad := coalesce(
    nullif(new.raw_user_meta_data ->> 'id_ciudad', '')::integer,
    (select min(id_ciudad) from public.ciudad)
  );

  insert into public.usuario (id_usuario, nombre, id_ciudad)
  values (new.id, v_nombre, v_ciudad);

  insert into public.organizador (nombre, id_usuario)
  values (v_nombre, new.id);

  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function handle_new_user();

-- ---------------------------------------------------------------------------
-- 5. Busqueda por significado (tsvector + GIN)
-- ---------------------------------------------------------------------------
-- Una columna GENERATED no puede leer otras tablas, y categoria y etiquetas
-- viven en otras tablas. Por eso el vector se calcula en funcion y lo mantienen
-- triggers. Pesos: A titulo, B categoria y etiquetas, C eslogan, D descripcion.

create function evento_vector(
  p_id_evento    integer,
  p_titulo       text,
  p_eslogan      text,
  p_descripcion  text,
  p_id_categoria integer
)
returns tsvector
language sql
stable
security definer
set search_path = ''
as $$
  select
    setweight(to_tsvector('public.peip_es', coalesce(p_titulo, '')), 'A')
    || setweight(to_tsvector('public.peip_es',
         coalesce((select c.nombre from public.categoria c
                   where c.id_categoria = p_id_categoria), '')
         || ' ' ||
         coalesce((select string_agg(t.nombre, ' ')
                   from public.evento_etiqueta ee
                   join public.etiqueta t on t.id_etiqueta = ee.id_etiqueta
                   where ee.id_evento = p_id_evento), '')), 'B')
    || setweight(to_tsvector('public.peip_es', coalesce(p_eslogan, '')), 'C')
    || setweight(to_tsvector('public.peip_es', coalesce(p_descripcion, '')), 'D');
$$;

create function evento_set_busqueda()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.busqueda := public.evento_vector(
    new.id_evento, new.titulo, new.eslogan, new.descripcion, new.id_categoria
  );
  return new;
end;
$$;

create trigger evento_busqueda_trg
  before insert or update on evento
  for each row execute function evento_set_busqueda();

-- Recalcula el vector de un evento cuando cambian sus etiquetas. Tocar la fila
-- dispara evento_busqueda_trg.
create function evento_etiqueta_refrescar()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.evento
     set titulo = titulo
   where id_evento = coalesce(new.id_evento, old.id_evento);
  return null;
end;
$$;

create trigger evento_etiqueta_busqueda_trg
  after insert or delete on evento_etiqueta
  for each row execute function evento_etiqueta_refrescar();

-- Si se renombra una categoria o una etiqueta, se refrescan sus eventos.
create function categoria_refrescar()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.evento set titulo = titulo where id_categoria = new.id_categoria;
  return null;
end;
$$;

create trigger categoria_busqueda_trg
  after update of nombre on categoria
  for each row execute function categoria_refrescar();

create function etiqueta_refrescar()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.evento set titulo = titulo
   where id_evento in (select id_evento from public.evento_etiqueta
                       where id_etiqueta = new.id_etiqueta);
  return null;
end;
$$;

create trigger etiqueta_busqueda_trg
  after update of nombre on etiqueta
  for each row execute function etiqueta_refrescar();

-- Convierte la consulta en un tsquery. Cada palabra (sin tildes, de mas de dos
-- letras) forma un grupo con sus equivalentes de la tabla sinonimo, unidos con
-- OR: "liderazgo" se vuelve (liderazg | leadership). Las palabras vacias
-- ("algo", "sobre", "para") las descarta el diccionario de espanol.
--   p_todas = true : los grupos se unen con AND (el evento cubre todos los
--                    conceptos de la consulta).
--   p_todas = false: los grupos se unen con OR (cubre alguno).
-- Devuelve null si la consulta no tiene ninguna palabra util.
create function peip_tsquery(p_consulta text, p_todas boolean default true)
returns tsquery
language plpgsql
stable
set search_path = ''
set client_min_messages = error
as $$
declare
  v_q       tsquery;
  v_grupo   tsquery;
  v_palabra text;
  v_sin     text;
begin
  for v_palabra in
    select distinct w
    from regexp_split_to_table(
           extensions.unaccent('extensions.unaccent'::regdictionary,
                               lower(coalesce(p_consulta, ''))),
           '[^a-z0-9]+') as w
    where length(w) > 2
  loop
    v_grupo := plainto_tsquery('public.peip_es', v_palabra);
    for v_sin in
      select s.equivalente from public.sinonimo s where s.termino = v_palabra
    loop
      v_grupo := v_grupo || plainto_tsquery('public.peip_es', v_sin);
    end loop;

    if numnode(v_grupo) = 0 then
      continue; -- palabra vacia: no aporta nada
    end if;

    if v_q is null then
      v_q := v_grupo;
    elsif p_todas then
      v_q := v_q && v_grupo;
    else
      v_q := v_q || v_grupo;
    end if;
  end loop;
  return v_q;
end;
$$;

-- ---------------------------------------------------------------------------
-- 6. Afinidad (reemplaza calcularAfinidad de lib/utils/busqueda.dart)
-- ---------------------------------------------------------------------------
-- puntaje = 2 si la categoria esta en los intereses
--         + suma de pesos de las etiquetas del evento
--         + 1 si el evento es en la ciudad del usuario
-- normalizado = clamp(puntaje / 4, 0, 1), mapeado a 63..84 para que no se vea
-- un 98% inventado. Corre como el usuario que llama, asi que la RLS limita los
-- datos que lee a los propios.

create function afinidad(
  p_id_evento  integer,
  p_id_usuario uuid default auth.uid()
)
returns integer
language sql
stable
set search_path = ''
as $$
  select round(
    63 + least(greatest((
        (case when exists (
           select 1
           from public.usuario_interes ui
           join public.evento e on e.id_categoria = ui.id_categoria
           where ui.id_usuario = p_id_usuario and e.id_evento = p_id_evento
         ) then 2 else 0 end)
      + coalesce((
           select sum(ue.peso)
           from public.usuario_etiqueta ue
           join public.evento_etiqueta ee on ee.id_etiqueta = ue.id_etiqueta
           where ue.id_usuario = p_id_usuario and ee.id_evento = p_id_evento
         ), 0)
      + (case when exists (
           select 1
           from public.usuario u
           join public.evento e on e.id_ciudad = u.id_ciudad
           where u.id_usuario = p_id_usuario and e.id_evento = p_id_evento
         ) then 1 else 0 end)
    ) / 4.0, 0), 1) * 21
  )::integer;
$$;

