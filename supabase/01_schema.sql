-- PEIP, entrega 4. Bloque A: esquema, busqueda de texto completo y afinidad.
--
-- Traduccion del MER de la entrega 1 (Oracle) a Postgres 17 / Supabase.
-- Orden de ejecucion: 01_schema.sql, 02_policies.sql, 03_seed.sql.
--
-- Cambios respecto al MER:
--   * usuario ya no guarda correo ni hash: la credencial vive en auth.users y
--     usuario.id_usuario es el uuid de esa cuenta.
--   * organizador.id_usuario liga una cuenta con su organizador (una misma
--     cuenta puede ser asistente y organizador). Lo crea el trigger de alta.
--   * evento.busqueda es el tsvector de la busqueda por significado.
--   * evento.imagen_path guarda la ruta del archivo en Storage (bloque D).
--   * personalizacion_activa y todo_el_dia pasan de CHAR(1) a boolean.
--   * las fechas son timestamptz. Desde Flutter hay que enviar
--     dateTime.toUtc().toIso8601String().
--
-- Para reiniciar la base desde cero (borra TODOS los datos de PEIP):
--   drop view if exists v_evento cascade;
--   drop table if exists sinonimo, usuario_etiqueta, usuario_interes,
--     evento_guardado, evento_etiqueta, busqueda_reciente, reserva,
--     tipo_entrada, evento, serie_evento, etiqueta, organizador, usuario,
--     categoria, ciudad cascade;
--   drop text search configuration if exists public.peip_es;
--   drop function if exists handle_new_user() cascade;

-- ---------------------------------------------------------------------------
-- 1. Extensiones y configuracion de busqueda
-- ---------------------------------------------------------------------------

create extension if not exists unaccent with schema extensions;

-- Configuracion de texto en espanol que ademas ignora tildes: "analitica" y
-- "analítica" producen el mismo lexema.
create text search configuration public.peip_es (copy = pg_catalog.spanish);

alter text search configuration public.peip_es
  alter mapping for asciiword, asciihword, hword_asciipart, hword, hword_part, word
  with extensions.unaccent, spanish_stem;

-- ---------------------------------------------------------------------------
-- 2. Tablas
-- ---------------------------------------------------------------------------

create table ciudad (
  id_ciudad integer generated by default as identity primary key,
  nombre    varchar(80) not null unique
);

create table categoria (
  id_categoria integer generated by default as identity primary key,
  nombre       varchar(80) not null unique,
  icono        varchar(60),
  color        varchar(20)
);

create table etiqueta (
  id_etiqueta integer generated by default as identity primary key,
  nombre      varchar(60) not null unique
);

create table usuario (
  id_usuario             uuid primary key references auth.users (id) on delete cascade,
  nombre                 varchar(100) not null,
  personalizacion_activa boolean not null default true,
  id_ciudad              integer not null references ciudad (id_ciudad)
);

create table organizador (
  id_organizador integer generated by default as identity primary key,
  nombre         varchar(120) not null,
  -- null para organizadores institucionales que no son una cuenta de la app
  id_usuario     uuid unique references usuario (id_usuario) on delete set null
);

create table serie_evento (
  id_serie       integer generated by default as identity primary key,
  nombre         varchar(150) not null,
  periodicidad   varchar(30) not null,
  id_organizador integer not null references organizador (id_organizador),
  id_categoria   integer not null references categoria (id_categoria)
);

create table evento (
  id_evento          integer generated by default as identity primary key,
  titulo             varchar(200) not null,
  eslogan            varchar(250),
  descripcion        varchar(2000),
  fecha_inicio       timestamptz not null,
  fecha_fin          timestamptz not null,
  todo_el_dia        boolean not null default false,
  lugar              varchar(150) not null,
  estado             varchar(20) not null default 'borrador',
  aforo              integer,
  imagen_path        text,
  id_categoria       integer not null references categoria (id_categoria),
  id_organizador     integer not null references organizador (id_organizador),
  id_ciudad          integer not null references ciudad (id_ciudad),
  id_serie           integer references serie_evento (id_serie) on delete set null,
  id_evento_anterior integer references evento (id_evento) on delete set null,
  busqueda           tsvector,
  constraint ck_evento_estado check (estado in ('borrador', 'publicado', 'cancelado')),
  constraint ck_evento_fechas check (fecha_fin >= fecha_inicio),
  constraint ck_evento_aforo check (aforo is null or aforo > 0)
);

create table tipo_entrada (
  id_entrada integer generated by default as identity primary key,
  nombre     varchar(80) not null,
  precio     integer not null default 0 check (precio >= 0), -- pesos, 0 = gratis
  beneficios varchar(250),
  id_evento  integer not null references evento (id_evento) on delete cascade
);

create table reserva (
  id_reserva    integer generated by default as identity primary key,
  cantidad      integer not null check (cantidad between 1 and 10),
  codigo_qr     varchar(60) not null unique
                default ('PEIP-' || upper(substr(gen_random_uuid()::text, 1, 12))),
  fecha_reserva timestamptz not null default now(),
  fecha_uso     timestamptz, -- null si no se ha usado
  id_usuario    uuid not null references usuario (id_usuario) on delete cascade,
  id_entrada    integer not null references tipo_entrada (id_entrada) on delete cascade
);

create table busqueda_reciente (
  id_busqueda integer generated by default as identity primary key,
  texto       varchar(250) not null,
  fecha       timestamptz not null default now(),
  id_usuario  uuid not null references usuario (id_usuario) on delete cascade
);

-- tablas intermedias (N a N)

create table evento_etiqueta (
  id_evento   integer not null references evento (id_evento) on delete cascade,
  id_etiqueta integer not null references etiqueta (id_etiqueta) on delete cascade,
  primary key (id_evento, id_etiqueta)
);

create table evento_guardado (
  id_usuario     uuid not null references usuario (id_usuario) on delete cascade,
  id_evento      integer not null references evento (id_evento) on delete cascade,
  fecha_guardado timestamptz not null default now(),
  primary key (id_usuario, id_evento)
);

create table usuario_interes (
  id_usuario   uuid not null references usuario (id_usuario) on delete cascade,
  id_categoria integer not null references categoria (id_categoria) on delete cascade,
  primary key (id_usuario, id_categoria)
);

create table usuario_etiqueta (
  id_usuario  uuid not null references usuario (id_usuario) on delete cascade,
  id_etiqueta integer not null references etiqueta (id_etiqueta) on delete cascade,
  peso        numeric(5, 2) not null check (peso between 0 and 1),
  primary key (id_usuario, id_etiqueta)
);

-- Equivalencias espanol a ingles para la busqueda por significado. Las
-- categorias y etiquetas del catalogo estan en ingles y las consultas en
-- espanol. termino va en minusculas y sin tildes.
create table sinonimo (
  termino     varchar(60) not null,
  equivalente varchar(60) not null,
  primary key (termino, equivalente)
);

comment on table evento is 'El tsvector de busqueda (columna busqueda) lo mantienen triggers; no se escribe a mano.';
comment on column evento.id_evento_anterior is 'Edicion anterior del mismo evento (autorreferencia opcional).';
comment on column evento.imagen_path is 'Ruta del archivo de portada dentro del bucket de Storage.';
comment on column reserva.fecha_uso is 'Nulo si la entrada no se ha usado; con fecha si el usuario asistio.';
comment on column usuario_etiqueta.peso is 'Peso inferido de la etiqueta para el usuario, entre 0 y 1.';

